static void initNick(char** nicks, int value, const char* prefix, const char* name)
{
    assert(nicks[value] == NULL);
    nicks[value] = malloc(strlen(name) + 1);
    strcpy(nicks[value], name);
    tcStrlwr(nicks[value]);
}

